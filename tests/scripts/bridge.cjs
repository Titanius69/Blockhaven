const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {JSDOM} = require('jsdom');
const dom = new JSDOM(`<body><div data-window-drag><span id="drag">Title</span><button data-action="window_minimize">Minimize</button></div><div data-window-resize="east"></div><button data-action="open_version" data-value="example">Version folder</button><form data-action="save_settings"><input name="discord_application_id" value="123456789012345678"><input type="checkbox" name="discord_enabled" checked><button type="submit">Save</button></form><div id="status"></div></body>`, {runScripts:'outside-only'});
const {window} = dom;
const messages = [];
window.ipc = {postMessage: text => messages.push(JSON.parse(text))};
window.eval(fs.readFileSync(path.join(__dirname,'../../crates/fastchapp-desktop/src/bridge.js'),'utf8'));
window.document.querySelector('[data-action="open_version"]').click();
assert.equal(messages.at(-1).action,'open_version');
assert.equal(messages.at(-1).value,'example');
window.document.querySelector('form').dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));
assert.deepEqual(messages.at(-1).fields,{discord_application_id:['123456789012345678'],discord_enabled:['on']});
const title = window.document.querySelector('#drag');
title.dispatchEvent(new window.MouseEvent('mousedown',{bubbles:true,button:0,detail:1}));
assert.equal(messages.at(-1).action,'window_drag');
title.dispatchEvent(new window.MouseEvent('dblclick',{bubbles:true}));
assert.equal(messages.at(-1).action,'window_toggle_maximize');
window.document.querySelector('[data-window-resize]').dispatchEvent(new window.MouseEvent('mousedown',{bubbles:true,button:0}));
assert.equal(messages.at(-1).action,'window_resize');
assert.equal(messages.at(-1).value,'east');
window.FastChapp.apply({patches:[{op:'text',selector:'#status',value:'Ready'}],window:{visible:false,focus:false}});
assert.equal(window.document.querySelector('#status').textContent,'Ready');
assert.equal(window.document.body.hidden,false);
console.log('PASS: folder actions, Discord form, native controls and generic DOM patches');
window.close();
